# Regenerates docs/reference/cli.md from each binary's own usage text, so the
# reference cannot drift from the code: edit the usage in cmd/<name>/main.go,
# run `make cli-reference`, commit both.
set -euo pipefail
cd "$(dirname "$0")/.."
make build >/dev/null
out=docs/reference/cli.md
root="$(pwd)"
{
  echo "# Command-line reference"
  echo
  echo "Generated by \`scripts/gen_cli_reference.sh\` (\`make cli-reference\`) from the"
  echo "usage text each binary prints for \`help\` / \`-h\`. The four release binaries"
  echo "are \`sagvd\`, \`acp-compute\`, \`acpctl\` and \`acp-bootstrap\`; \`acp-demo\` is a"
  echo "development aid and is not released. Configuration files, bundle formats and"
  echo "the audit schema are described in \`docs/operator/\` and \`docs/spec/\`."
  for b in sagvd acp-compute acpctl acp-bootstrap acp-demo; do
    echo
    echo "## $b"
    echo
    echo '```text'
    "bin/$b" -h 2>&1 | sed "s#${root}/##g" || true
    echo '```'
  done
} > "$out"
echo "wrote $out"
