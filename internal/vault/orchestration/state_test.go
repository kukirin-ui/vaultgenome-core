func TestCanTransition_IllegalReturnsFalse(t *testing.T) {
	t.Parallel()
	// Skip trust → audit directly — that bypasses session issuance.
	require.False(t, CanTransition(StateTrust, StateAudit, ""))
	// Validation → Session is a backward edge, must not exist.
	require.False(t, CanTransition(StateValidation, StateSession, ""))
	// Unknown trigger on an otherwise legal arc.
	require.False(t, CanTransition(StateRequest, StateTrust, "not.a.real.trigger"))
}

